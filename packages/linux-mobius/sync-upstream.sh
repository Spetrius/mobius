#!/bin/bash
# Regenerate linux-mobius from CachyOS's linux-cachyos-bore PKGBUILD.
# We only borrow their patched source tree and config; the kernel is built by us.
# Usage: ./sync-upstream.sh [path-to-linux-cachyos-checkout]
set -euo pipefail

here="$(cd "$(dirname "$0")" && pwd)"
up="${1:-}"
if [[ -z "$up" ]]; then
    up="$(mktemp -d)"
    git clone -q --depth 1 https://github.com/CachyOS/linux-cachyos.git "$up"
fi
src="$up/linux-cachyos-bore"
[[ -f "$src/PKGBUILD" ]] || { echo "no PKGBUILD in $src" >&2; exit 1; }

# Compressed debug info: same packages (debug is stripped), far smaller build tree. Keeps BTF for sched-ext.
sed -e '/^# CONFIG_DEBUG_INFO_COMPRESSED_ZSTD is not set/d' \
    -e 's/^CONFIG_DEBUG_INFO_COMPRESSED_NONE=y/# CONFIG_DEBUG_INFO_COMPRESSED_NONE is not set\nCONFIG_DEBUG_INFO_COMPRESSED_ZSTD=y/' \
    "$src/config" > "$here/config"
old_sum="$(b2sum "$src/config" | cut -d' ' -f1)"
new_sum="$(b2sum "$here/config" | cut -d' ' -f1)"
commit="$(git -C "$up" rev-parse HEAD 2>/dev/null || echo unknown)"

sed \
    -e 's|^pkgbase="linux-\$_pkgsuffix"|pkgbase="linux-mobius"|' \
    -e 's|^_kernuname=.*|_kernuname="${pkgver}-${pkgrel}-mobius"|' \
    -e 's|^: "\${_processor_opt:=}"|: "${_processor_opt:=generic_v3}"|' \
    -e 's|^export KBUILD_BUILD_HOST=.*|export KBUILD_BUILD_HOST=mobius|' \
    -e "s|^pkgdesc=.*|pkgdesc='Mobius kernel: BORE scheduler + CachyOS patchset, x86-64-v3, O3, 1000Hz'|" \
    -e "s|'$old_sum'|'$new_sum'|" \
    "$src/PKGBUILD" > "$here/PKGBUILD"
grep -q "$new_sum" "$here/PKGBUILD" || { echo "config checksum not updated" >&2; exit 1; }

# Header so nobody hand-edits the generated file and loses it on next sync
sed -i "1i # GENERATED by sync-upstream.sh from CachyOS/linux-cachyos@${commit} (linux-cachyos-bore).\n# Edit sync-upstream.sh, not this file.\n" "$here/PKGBUILD"

grep -q '^pkgbase="linux-mobius"' "$here/PKGBUILD" || { echo "pkgbase sed failed, upstream format changed" >&2; exit 1; }
grep -q 'generic_v3' "$here/PKGBUILD" || { echo "processor_opt sed failed" >&2; exit 1; }
echo "linux-mobius synced to $(grep -m1 "^_major=" "$here/PKGBUILD" | cut -d= -f2).$(grep -m1 "^_minor=" "$here/PKGBUILD" | cut -d= -f2) from $commit"
